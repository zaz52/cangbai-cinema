from pathlib import Path
from playwright.sync_api import sync_playwright
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import threading, os
root=Path(__file__).resolve().parents[1]/'public';os.chdir(root)
server=ThreadingHTTPServer(('127.0.0.1',8891),SimpleHTTPRequestHandler)
threading.Thread(target=server.serve_forever,daemon=True).start()
items=[dict(id=f'film-{i:02d}',title=t,year=1940+i,type='公开影像',image=f'https://archive.org/services/img/film-{i:02d}',sourceCount=1,sourceIds=[f'film-{i:02d}'],source='Internet Archive',sourceUrl=f'https://archive.org/details/film-{i:02d}',description='历史影像样例') for i,t in enumerate(['A Trip Through History','The Great City','Nature in Motion','A Film About Time','Beyond the Valley','Everyday America','The Bright Future','Living Landscapes','People and Places','The Silent Moment'])]
with sync_playwright() as p:
 b=p.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'])
 page=b.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.route('**/api/search?**',lambda r:r.fulfill(json={'results':items,'total':134,'page':1,'provider':'Internet Archive'}))
 def detail(route):
  id=route.request.url.split('id=')[-1];o=next((m for m in items if m['id']==id),items[0]);route.fulfill(json={**o,'license':'Creative Commons Attribution','rightsNote':'Demo testing fixture','videos':[{'name':'example.mp4','format':'MPEG4','url':'https://download.blender.org/peach/bigbuckbunny_movies/BigBuckBunny_320x180.mp4'}]})
 page.route('**/api/detail?**',detail)
 page.route('https://archive.org/services/img/**', lambda r:r.abort())
 page.route('https://cdn.jsdelivr.net/**',lambda r:r.fulfill(body='',content_type='application/javascript'))
 page.route('**/api/catalog?**',lambda r:r.fulfill(json={'updatedAt':'2026-10-12','results':[{'id':'test-directory','name':'示例影视导航','url':'https://example.com','category':'online_video','stars':4,'status':'verified','checked':'2026-10-12','risk':'unknown','summary':'示例导航，不代表已接入 API'}]}))
 page.goto('http://127.0.0.1:8891/',wait_until='domcontentloaded')
 page.wait_for_selector('.poster-card',timeout=15000)
 print('Cards',page.locator('.poster-card').count(),'Top nav',page.locator('.top-nav a').all_text_contents())
 page.screenshot(path='/mnt/data/松柏-新版首页效果.png',full_page=True)
 page.locator('.poster-art').first.click(position={'x':60,'y':100})
 page.wait_for_selector('.detail-info')
 print('Details',page.locator('.detail-info h2').inner_text())
 page.locator('.detail-info [data-action="play"]').first.click()
 print('Video',page.locator('.real-player video').count())
 page.keyboard.press('Escape')
 print('Modal closed',page.locator('.overlay.open').count())
 page.locator('.fav').first.click()
 print('Saved',page.evaluate("Object.keys(JSON.parse(localStorage.getItem('songbai-fav-v2'))).length"))
 page.locator('#globalSearch').fill('nature')
 page.wait_for_timeout(800)
 print('Search active',page.locator('.section-title').first.inner_text())
 page.screenshot(path='/mnt/data/松柏-新版搜索效果.png',full_page=False)
 page.set_viewport_size({'width':390,'height':844})
 page.locator('#globalSearch').fill('')
 page.wait_for_timeout(800)
 page.screenshot(path='/mnt/data/松柏-新版手机效果.png',full_page=True)
 print('Mobile nav',page.locator('#mobileNav button').count())
 page.locator('[data-nav="影视源目录"]').first.click()
 page.wait_for_selector('.directory-card')
 print('Directory cards',page.locator('.directory-card').count())
 print('Errors',errors)
 b.close()
server.shutdown()
